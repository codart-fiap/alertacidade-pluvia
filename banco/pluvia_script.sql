BEGIN;

-- ---------------------------------------------------------------------
-- 1) Recriacao do esquema (ordem inversa das dependencias)
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS alerta         CASCADE;
DROP TABLE IF EXISTS leitura_sensor CASCADE;
DROP TABLE IF EXISTS sensor         CASCADE;
DROP TABLE IF EXISTS ponto_seguro   CASCADE;
DROP TABLE IF EXISTS area_risco     CASCADE;
DROP TABLE IF EXISTS usuario        CASCADE;

-- ---------------------------------------------------------------------
-- 2) Tabelas
-- ---------------------------------------------------------------------

-- Pessoas que acessam a API (a senha nunca e guardada: apenas o hash BCrypt)
CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL,
    senha_hash  VARCHAR(255) NOT NULL,
    perfil      VARCHAR(20)  NOT NULL,
    CONSTRAINT pk_usuario        PRIMARY KEY (id),
    CONSTRAINT uq_usuario_email  UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'CIDADAO'))
);

-- Regioes monitoradas, desenhadas no mapa como um circulo (centro + raio)
CREATE TABLE area_risco (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome         VARCHAR(120)     NOT NULL,
    latitude     DOUBLE PRECISION NOT NULL,
    longitude    DOUBLE PRECISION NOT NULL,
    raio_metros  DOUBLE PRECISION NOT NULL,
    nivel_risco  VARCHAR(10)      NOT NULL,
    ativa        BOOLEAN          NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_area_risco       PRIMARY KEY (id),
    CONSTRAINT ck_area_latitude    CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_area_longitude   CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_area_raio        CHECK (raio_metros > 0),
    CONSTRAINT ck_area_nivel       CHECK (nivel_risco IN ('BAIXO', 'MEDIO', 'ALTO'))
);

-- Locais de abrigo para onde a pessoa e orientada a ir
CREATE TABLE ponto_seguro (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(120)     NOT NULL,
    latitude   DOUBLE PRECISION NOT NULL,
    longitude  DOUBLE PRECISION NOT NULL,
    CONSTRAINT pk_ponto_seguro  PRIMARY KEY (id),
    CONSTRAINT ck_ponto_latitude  CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_ponto_longitude CHECK (longitude BETWEEN -180 AND 180)
);

-- Dispositivos de medicao (regua de nivel do rio, pluviometro) de cada area
CREATE TABLE sensor (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR(120)     NOT NULL,
    tipo           VARCHAR(20)      NOT NULL,
    area_risco_id  BIGINT           NOT NULL,
    limite_alerta  DOUBLE PRECISION NOT NULL,
    CONSTRAINT pk_sensor        PRIMARY KEY (id),
    CONSTRAINT fk_sensor_area   FOREIGN KEY (area_risco_id) REFERENCES area_risco (id) ON DELETE RESTRICT,
    CONSTRAINT ck_sensor_tipo   CHECK (tipo IN ('NIVEL_RIO', 'CHUVA')),
    CONSTRAINT ck_sensor_limite CHECK (limite_alerta > 0)
);

-- Cada medicao enviada por um sensor (nivel do rio em cm, chuva em mm/h)
CREATE TABLE leitura_sensor (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sensor_id  BIGINT           NOT NULL,
    valor      DOUBLE PRECISION NOT NULL,
    data_hora  TIMESTAMP        NOT NULL,
    CONSTRAINT pk_leitura_sensor   PRIMARY KEY (id),
    CONSTRAINT fk_leitura_sensor   FOREIGN KEY (sensor_id) REFERENCES sensor (id) ON DELETE RESTRICT,
    CONSTRAINT ck_leitura_valor    CHECK (valor >= 0)
);

-- Alerta gerado quando uma leitura atinge o limite do sensor.
-- A area e o horario NAO ficam aqui: saem da leitura (alerta -> leitura -> sensor -> area_risco).
-- Cada leitura gera no maximo um alerta (UNIQUE em leitura_id: relacao 1 para 0..1).
CREATE TABLE alerta (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    leitura_id  BIGINT       NOT NULL,
    nivel       VARCHAR(10)  NOT NULL,
    mensagem    VARCHAR(255) NOT NULL,
    CONSTRAINT pk_alerta         PRIMARY KEY (id),
    CONSTRAINT uq_alerta_leitura UNIQUE (leitura_id),
    CONSTRAINT fk_alerta_leitura FOREIGN KEY (leitura_id) REFERENCES leitura_sensor (id) ON DELETE RESTRICT,
    CONSTRAINT ck_alerta_nivel   CHECK (nivel IN ('BAIXO', 'MEDIO', 'ALTO'))
);

-- Indices para as consultas mais comuns (as chaves primarias e UNIQUE ja criam o seu proprio indice)
CREATE INDEX idx_sensor_area           ON sensor (area_risco_id);
CREATE INDEX idx_leitura_sensor_tempo  ON leitura_sensor (sensor_id, data_hora DESC);

COMMENT ON TABLE usuario        IS 'Pessoas que acessam a API: perfis ADMIN e CIDADAO';
COMMENT ON TABLE area_risco     IS 'Regioes monitoradas, desenhadas no mapa como circulo (centro + raio)';
COMMENT ON TABLE ponto_seguro   IS 'Locais de abrigo indicados na recomendacao';
COMMENT ON TABLE sensor         IS 'Sensores de cada area (regua de nivel do rio e pluviometro) e seu limite de alerta';
COMMENT ON TABLE leitura_sensor IS 'Medicoes enviadas pelos sensores';
COMMENT ON TABLE alerta         IS 'Alerta gerado por uma leitura que atingiu o limite do sensor';

