-- Alertas: toda leitura que atingiu o limite do sensor gera um alerta, com a MESMA regra da API:
--   valor/limite < 1,2 -> BAIXO | de 1,2 ate < 1,5 -> MEDIO | a partir de 1,5 -> ALTO
INSERT INTO alerta (leitura_id, nivel, mensagem)
SELECT l.id,
       n.nivel,
       format('Risco de enchente (%s) em %s: %s em %s %s (limite %s %s)',
              n.nivel,
              a.nome,
              CASE s.tipo WHEN 'NIVEL_RIO' THEN 'Nível do rio' ELSE 'Chuva' END,
              replace(to_char(l.valor, 'FM999990.0'), '.', ','),
              CASE s.tipo WHEN 'NIVEL_RIO' THEN 'cm' ELSE 'mm/h' END,
              replace(to_char(s.limite_alerta, 'FM999990.0'), '.', ','),
              CASE s.tipo WHEN 'NIVEL_RIO' THEN 'cm' ELSE 'mm/h' END)
FROM leitura_sensor l
JOIN sensor s      ON s.id = l.sensor_id
JOIN area_risco a  ON a.id = s.area_risco_id
CROSS JOIN LATERAL (
    SELECT CASE WHEN l.valor / s.limite_alerta >= 1.5 THEN 'ALTO'
                WHEN l.valor / s.limite_alerta >= 1.2 THEN 'MEDIO'
                ELSE 'BAIXO' END AS nivel
) n
WHERE l.valor >= s.limite_alerta
ORDER BY l.data_hora, l.id;

