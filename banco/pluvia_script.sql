-- ---------------------------------------------------------------------
-- 4) Conferencia da carga inicial
-- ---------------------------------------------------------------------
SELECT 'usuario' AS tabela, COUNT(*) AS linhas FROM usuario
UNION ALL SELECT 'area_risco',     COUNT(*) FROM area_risco
UNION ALL SELECT 'ponto_seguro',   COUNT(*) FROM ponto_seguro
UNION ALL SELECT 'sensor',         COUNT(*) FROM sensor
UNION ALL SELECT 'leitura_sensor', COUNT(*) FROM leitura_sensor
UNION ALL SELECT 'alerta',         COUNT(*) FROM alerta;
